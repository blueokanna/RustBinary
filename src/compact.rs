//! # Compact schema-guided binary profile
//!
//! The **self-describing** profile (see `crate::ser` / `crate::decoder`)
//! trades compactness for dynamic flexibility: every value carries a one-byte
//! type tag, struct fields are written as named object keys, and containers
//! are `0xff`-terminated. For statically known types that overhead dominates:
//! a `Vec<u8>` becomes `array tag, element tag, byte, element tag, byte, …,
//! end tag`, and numeric arrays pay one tag per element.
//!
//! This module provides the complementary **compact** profile for statically
//! typed values. The encoder knows the schema at compile time, so the wire
//! carries **no type tags and no field names**; containers use length prefixes
//! instead of terminators; `Option<T>` is a single presence byte; enums write
//! only a compact variant discriminant. Dynamic `Value`s, untagged enums and
//! `FormatEncoder`-driven types stay on the self-describing profile and never
//! drag down the static path.
//!
//! The two layers are separate by design:
//!
//! - [`CompactEncode`] / [`CompactDecode`] — a hot path generated by the
//!   `#[derive(rustbinary::CompactBinary)]` macro (or hand-written) that
//!   encodes/decodes straight into the wire with no nextjson event dispatch,
//!   no field-name handling and no per-value tag match.
//! - [`nextjson::FormatEncoder`] / [`nextjson::FormatDecoder`] — the existing
//!   generic path, kept for dynamic and framework-neutral values.
//!
//! # Wire layout
//!
//! The compact profile is a **headerless**, length-prefixed stream. Integer
//! widths and byte order are fixed (canonical little-endian marker-varints,
//! little-endian floats) and do **not** follow the base [`crate::Config`]
//! `Endian` / `IntEncoding` knobs — this keeps the format stable and the fast
//! paths allocation-free. The base config's *resource* knobs still apply:
//! `limit`, `collection_limit`, `depth_limit` and `trailing`.
//!
//! ```text
//! unit ()            : (nothing)
//! bool               : 1 byte 0x00 | 0x01
//! u8 / i8            : 1 raw byte
//! u16..u128          : canonical marker varint (little endian)
//! i16..i128          : ZigZag marker varint (little endian)
//! f32 / f64          : 4 / 8 bytes, little endian
//! char               : varint code point
//! str / String       : varint byte_len + UTF-8 bytes
//! &[u8] / Vec<u8>    : varint len + raw bytes          (memcpy fast path)
//! Vec<u16/u32/u64>   : varint len + tight varint loop
//! Vec<i16/i32/i64>   : varint len + tight ZigZag loop
//! Vec<f32/f64>       : varint len + bulk little-endian payload
//! Option<T>          : 1 byte 0x00 (None) | 0x01 (Some) + T
//! Vec<T> / &[T]      : varint len + elements
//! [T; N]             : N elements (no length prefix)
//! tuple              : elements in declaration order
//! map<K, V>          : varint len + (K V) pairs
//! enum               : varint discriminant + variant payload
//! ```
//!
//! Struct fields are written in declaration order with no names; both sides
//! must share the same schema. For cross-version evolution use
//! [`crate::Config::with_schema_evolution`] (stable numeric field IDs) and for
//! schema-identity verification use [`crate::Config::with_fingerprint`] — both
//! compose with this profile through `with_compact_format()`.
//!
//! # Example
//!
//! ```
//! use nextjson::{NsonDeserialize, NsonSerialize};
//!
//! #[derive(Debug, PartialEq, NsonSerialize, NsonDeserialize, rustbinary::CompactBinary)]
//! struct Packet {
//!     sequence: u64,
//!     payload: Vec<u8>,
//! }
//!
//! let packet = Packet { sequence: 42, payload: b"hello".to_vec() };
//! // Compact path (schema-known direct codec).
//! let bytes = rustbinary::options().with_compact_format().serialize(&packet)?;
//! let decoded: Packet = rustbinary::options().with_compact_format().deserialize(&bytes)?;
//! assert_eq!(decoded, packet);
//! // The self-describing path still round-trips the same value.
//! let sdes = rustbinary::options().serialize(&packet)?;
//! assert_eq!(rustbinary::options().deserialize::<Packet>(&sdes)?, packet);
//! # Ok::<(), rustbinary::Error>(())
//! ```
//!
//! # Safety model
//!
//! The bulk fast paths reinterpret byte slices as `f64`/`f32`/`i8` slices only
//! after a compile-time-eliminated `type_equal` check and (on decode) an
//! alignment check, exactly like bincode 3's slice fast path. Every cast is
//! documented at its site and is read-only. The **general** `repr(Rust)`
//! object-to-bytes cast remains unsupported: users must keep that boundary.

