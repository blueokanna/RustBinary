/// Schema-known compact encoder (hot path).
///
/// Generated by `#[derive(rustbinary::CompactBinary)]` for structs and enums
/// and implemented for all supported standard types. The encoding is driven by
/// the static type — no type tags, no field names, length-prefixed containers.
pub trait CompactEncode {
    /// Writes this value's compact wire form into `writer`.
    fn encode_compact<W: EncodeWriter + ?Sized>(&self, writer: &mut W) -> Result<()>;
}

/// Schema-known compact decoder (hot path).
///
/// Implementations read from `cursor`, which owns the input lifetime `'de`, so
/// borrowed targets (`&'de str`, `&'de [u8]`) point directly into the input.
pub trait CompactDecode<'de>: Sized {
    /// Reads one value of this type from `cursor`.
    fn decode_compact(cursor: &mut CompactCursor<'de>) -> Result<Self>;
}

/// Compact-profile configuration, produced by [`Config::with_compact_format`].
///
/// Carries over the base config's resource policies (`limit`,
/// `collection_limit`, `depth_limit`, `trailing`) and ignores its byte-order /
/// integer-width knobs: the compact wire is always little-endian
/// marker-varint.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct CompactConfig {
    base: Config,
}

impl CompactConfig {
    pub(crate) const fn new(base: Config) -> Self {
        Self { base }
    }

    /// Returns the underlying resource-policy configuration.
    pub const fn base_config(self) -> Config {
        self.base
    }

    /// Always [`crate::BinaryProfile::CompactSchema`].
    pub const fn profile(self) -> crate::BinaryProfile {
        crate::BinaryProfile::CompactSchema
    }

    /// Serializes `value` into a fresh vector using the compact profile.
    pub fn serialize<T: CompactEncode + ?Sized>(self, value: &T) -> Result<Vec<u8>> {
        let mut output = Vec::new();
        {
            let mut writer = BoundedWriter::new(&mut output, self.base);
            value.encode_compact(&mut writer)?;
        }
        Ok(output)
    }

    /// Serializes into a caller-owned slice.
    ///
    /// On undersized output the written prefix is preserved and the error
    /// reports the exact required capacity.
    pub fn serialize_into_slice<T: CompactEncode + ?Sized>(
        self,
        output: &mut [u8],
        value: &T,
    ) -> Result<usize> {
        let mut writer = SliceWriter::new(output);
        {
            let mut bounded = BoundedWriter::new(&mut writer, self.base);
            value.encode_compact(&mut bounded)?;
        }
        writer.finish()
    }

    /// Computes the exact compact byte count without retaining output.
    pub fn serialized_size<T: CompactEncode + ?Sized>(self, value: &T) -> Result<u64> {
        let mut writer = CountWriter::new();
        value.encode_compact(&mut writer)?;
        Ok(writer.written())
    }

    /// Deserializes one compact value that may borrow from `input`.
    pub fn deserialize<'de, T: CompactDecode<'de>>(self, input: &'de [u8]) -> Result<T> {
        let mut cursor = CompactCursor::new(input, self.base);
        let value = T::decode_compact(&mut cursor)?;
        if self.base.trailing == TrailingBytes::Reject && cursor.position() != input.len() {
            return Err(Error::TrailingBytes {
                remaining: input.len() - cursor.position(),
            });
        }
        Ok(value)
    }
}

/// Bounded encoder sink used by [`CompactConfig`].
///
/// Enforces the base config's byte limit per write and its depth limit per
/// container, so hostile in-memory values cannot grow output past the policy.
struct BoundedWriter<W> {
    inner: W,
    limit: Option<u64>,
    depth_limit: usize,
    written: u64,
    depth: usize,
}

impl<W: EncodeWriter> BoundedWriter<W> {
    fn new(inner: W, config: Config) -> Self {
        Self {
            inner,
            limit: config.limit,
            depth_limit: config.depth_limit,
            written: 0,
            depth: 0,
        }
    }
}

impl<W: EncodeWriter> EncodeWriter for BoundedWriter<W> {
    fn write_all(&mut self, bytes: &[u8]) -> Result<()> {
        let amount =
            u64::try_from(bytes.len()).map_err(|_| Error::IntegerOverflow { target: "u64" })?;
        let next = self
            .written
            .checked_add(amount)
            .ok_or(Error::SizeLimit { limit: u64::MAX })?;
        if let Some(limit) = self.limit {
            if next > limit {
                return Err(Error::SizeLimit { limit });
            }
        }
        self.inner.write_all(bytes)?;
        self.written = next;
        Ok(())
    }

    fn enter_container(&mut self) -> Result<()> {
        if self.depth >= self.depth_limit {
            return Err(Error::Custom(
                "compact encode nesting depth limit exceeded".into(),
            ));
        }
        self.depth += 1;
        Ok(())
    }

    fn exit_container(&mut self) {
        debug_assert!(self.depth > 0);
        self.depth -= 1;
    }
}

// ---------------------------------------------------------------------------
// Compile-time type equality (dtolnay's non-static TypeId trick)
// ---------------------------------------------------------------------------

/// Compile-time type equality used to select bulk fast paths inside generic
/// container impls. The branch is constant after inlining and is eliminated at
/// monomorphization. `Target` must be a `'static` primitive; comparing against
/// lifetime-parameterized types is deliberately unsupported (see `unty`).
///
/// This is the same construction shipped in `unty` and used by bincode 3.
#[doc(hidden)]
pub fn __type_equal<Src: ?Sized, Target: ?Sized>() -> bool {
    non_static_type_id::<Src>() == non_static_type_id::<Target>()
}

fn non_static_type_id<T: ?Sized>() -> core::any::TypeId {
    trait NonStaticAny {
        fn get_type_id(&self) -> core::any::TypeId
        where
            Self: 'static;
    }

    impl<T: ?Sized> NonStaticAny for core::marker::PhantomData<T> {
        fn get_type_id(&self) -> core::any::TypeId
        where
            Self: 'static,
        {
            core::any::TypeId::of::<T>()
        }
    }

    // SAFETY: `get_type_id` never touches the (zero-sized) value — it only
    // reads `TypeId::of::<T>()`, a compile-time constant. Erasing the
    // (irrelevant) lifetime through the well-known dtolnay trick therefore
    // cannot cause any aliasing or value access; the reference is only used
    // to select the `'static`-bounded method. Identical to `unty`'s
    // `non_static_type_id`.
    let phantom = core::marker::PhantomData::<T>;
    unsafe {
        core::mem::transmute::<&dyn NonStaticAny, &(dyn NonStaticAny + 'static)>(&phantom)
            .get_type_id()
    }
}

