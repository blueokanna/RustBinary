impl<T: CompactEncode> CompactEncode for VecDeque<T> {
    fn encode_compact<W: EncodeWriter + ?Sized>(&self, writer: &mut W) -> Result<()> {
        encode_length(writer, self.len())?;
        writer.enter_container()?;
        let outcome = (|| {
            // `VecDeque` stores its elements in up to two contiguous slices;
            // route both through the bulk element encoder for the byte,
            // float, and numeric fast paths.
            let (head, tail) = self.as_slices();
            encode_elements(writer, head)?;
            encode_elements(writer, tail)
        })();
        writer.exit_container();
        outcome
    }
}

impl<'de, T: CompactDecode<'de>> CompactDecode<'de> for VecDeque<T> {
    fn decode_compact(cursor: &mut CompactCursor<'de>) -> Result<VecDeque<T>> {
        let len = cursor.read_length()?;
        cursor.enter_container(len)?;
        let outcome = (|| {
            let mut out = VecDeque::new();
            out.try_reserve(len)
                .map_err(|_| Error::SizeLimit { limit: u64::MAX })?;
            for _ in 0..len {
                out.push_back(T::decode_compact(cursor)?);
            }
            Ok(out)
        })();
        cursor.exit_container();
        outcome
    }
}

impl<K: CompactEncode, V: CompactEncode> CompactEncode for BTreeMap<K, V> {
    fn encode_compact<W: EncodeWriter + ?Sized>(&self, writer: &mut W) -> Result<()> {
        encode_length(writer, self.len())?;
        writer.enter_container()?;
        let outcome = (|| {
            for (key, value) in self {
                key.encode_compact(writer)?;
                value.encode_compact(writer)?;
            }
            Ok(())
        })();
        writer.exit_container();
        outcome
    }
}

impl<'de, K: CompactDecode<'de> + Ord, V: CompactDecode<'de>> CompactDecode<'de>
    for BTreeMap<K, V>
{
    fn decode_compact(cursor: &mut CompactCursor<'de>) -> Result<BTreeMap<K, V>> {
        let len = cursor.read_length()?;
        cursor.enter_container(len)?;
        let outcome = (|| {
            let mut out = BTreeMap::new();
            for _ in 0..len {
                let key = K::decode_compact(cursor)?;
                let value = V::decode_compact(cursor)?;
                // Duplicate keys would make the frame ambiguous; reject them.
                if out.insert(key, value).is_some() {
                    return Err(Error::Custom("duplicate map key".into()));
                }
            }
            Ok(out)
        })();
        cursor.exit_container();
        outcome
    }
}

