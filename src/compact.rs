impl<'de, T: CompactDecode<'de>> CompactDecode<'de> for Vec<T> {
    fn decode_compact(cursor: &mut CompactCursor<'de>) -> Result<Vec<T>> {
        let len = cursor.read_length()?;
        cursor.enter_container(len)?;
        let outcome: Result<Vec<T>> = (|| {
            if __type_equal::<T, u8>() {
                let bytes = cursor.read_bytes(len)?;
                let mut out = Vec::new();
                out.try_reserve_exact(len)
                    .map_err(|_| Error::SizeLimit { limit: u64::MAX })?;
                out.extend_from_slice(bytes);
                // SAFETY: this branch is compile-time eliminated unless
                // `T == u8`; `Vec<u8>` and `Vec<T>` then share layout.
                return Ok(unsafe { core::mem::transmute::<Vec<u8>, Vec<T>>(out) });
            }
            if __type_equal::<T, i8>() {
                let bytes = cursor.read_bytes(len)?;
                // SAFETY: `T == i8` (eliminated branch); `i8` has no invalid
                // bit patterns and 1-byte alignment.
                let values = unsafe {
                    core::slice::from_raw_parts(bytes.as_ptr().cast::<i8>(), bytes.len())
                };
                let mut out = Vec::new();
                out.try_reserve_exact(len)
                    .map_err(|_| Error::SizeLimit { limit: u64::MAX })?;
                out.copy_from_slice(values);
                return Ok(unsafe { core::mem::transmute::<Vec<i8>, Vec<T>>(out) });
            }
            if __type_equal::<T, f64>() {
                let values = read_f64_vec(cursor, len)?;
                return Ok(unsafe { core::mem::transmute::<Vec<f64>, Vec<T>>(values) });
            }
            if __type_equal::<T, f32>() {
                let values = read_f32_vec(cursor, len)?;
                return Ok(unsafe { core::mem::transmute::<Vec<f32>, Vec<T>>(values) });
            }
            if __type_equal::<T, u64>() {
                let values = cursor.read_varints_bulk(len)?;
                return Ok(unsafe { core::mem::transmute::<Vec<u64>, Vec<T>>(values) });
            }
            // Signed integers stay on the single-pass generic loop: ZigZag
            // reconstruction must happen inline, so a bulk pass followed by a
            // conversion pass would only add overhead.
            let mut out = Vec::new();
            out.try_reserve_exact(len)
                .map_err(|_| Error::SizeLimit { limit: u64::MAX })?;
            for _ in 0..len {
                out.push(T::decode_compact(cursor)?);
            }
            Ok(out)
        })();
        cursor.exit_container();
        outcome
    }
}

impl<T: CompactEncode, const N: usize> CompactEncode for [T; N] {
    fn encode_compact<W: EncodeWriter + ?Sized>(&self, writer: &mut W) -> Result<()> {
        // No length prefix (the width is part of the type); the bulk element
        // encoder gives byte/float/numeric arrays the same fast paths as
        // `Vec<T>`.
        encode_elements(writer, self)
    }
}

impl<'de, T: CompactDecode<'de>, const N: usize> CompactDecode<'de> for [T; N] {
    fn decode_compact(cursor: &mut CompactCursor<'de>) -> Result<[T; N]> {
        // Avoid a heap allocation for fixed-size arrays: fill a MaybeUninit
        // array and move it out once every slot is initialized.
        let mut slots: [core::mem::MaybeUninit<T>; N] =
            core::array::from_fn(|_| core::mem::MaybeUninit::uninit());
        for slot in &mut slots {
            slot.write(T::decode_compact(cursor)?);
        }
        // SAFETY: every slot was written by the loop above, which either
        // completed (all initialized) or returned early (cursor dropped, the
        // partially initialized slots are dropped with the array).
        Ok(unsafe { core::mem::transmute_copy(&slots) })
    }
}

