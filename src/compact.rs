/// Writes a `u128`-backed ZigZag value (used by the `i128` implementation).
fn encode_zigzag_i128<W: EncodeWriter + ?Sized>(writer: &mut W, value: i128) -> Result<()> {
    encode_varint_u128(writer, zigzag_encode(value))
}

/// Length of the leading run of single-byte varints (`byte ≤ 250`) in `input`.
///
/// Lets the bulk decoders consume numeric arrays as contiguous byte runs with
/// one bounds check per run instead of per element.
fn plain_varint_prefix(input: &[u8]) -> usize {
    #[cfg(feature = "simd")]
    return crate::simd::plain_varint_prefix(input);
    #[cfg(not(feature = "simd"))]
    input.iter().take_while(|&&byte| byte <= 250).count()
}

/// Writes one canonical marker-varint into `buffer`, which must have at least
/// 17 bytes free, and returns the number of bytes written.
///
/// Mirrors [`crate::canonical::encode_varint_le`] without materializing the
/// 17-byte temporary array; the drift-guard tests prove byte-identical output.
#[inline]
fn write_varint_into(buffer: &mut [u8], value: u64) -> usize {
    if value <= 250 {
        buffer[0] = value as u8;
        1
    } else if value <= 0xffff {
        buffer[0] = MARKER_U16;
        buffer[1..3].copy_from_slice(&(value as u16).to_le_bytes());
        3
    } else if value <= 0xffff_ffff {
        buffer[0] = MARKER_U32;
        buffer[1..5].copy_from_slice(&(value as u32).to_le_bytes());
        5
    } else {
        // `value` is a `u64`, so the widest reachable form is the 8-byte
        // payload; the 16-byte form is only produced by the `u128` writer.
        buffer[0] = MARKER_U64;
        buffer[1..9].copy_from_slice(&value.to_le_bytes());
        9
    }
}

