/// Bounded cursor over the compact wire input.
///
/// Owns the input lifetime `'de` so borrowed targets can point directly into
/// the input. All reads enforce the byte limit; collection lengths are checked
/// against the collection limit and nesting against the depth limit.
pub struct CompactCursor<'de> {
    input: &'de [u8],
    position: usize,
    /// Hard byte boundary for reads, when a per-read check is required.
    ///
    /// `None` when the input is no larger than the configured limit (or no
    /// limit is set): plain slice bounds then already enforce the byte limit,
    /// so the hot loops carry a loop-invariant branch that the compiler
    /// hoists away instead of a per-element limit check.
    limit_end: Option<usize>,
    collection_limit: Option<u64>,
    depth_limit: usize,
    depth: usize,
}

impl<'de> CompactCursor<'de> {
    pub(crate) fn new(input: &'de [u8], config: Config) -> Self {
        let limit_end = config.limit.and_then(|limit| {
            usize::try_from(limit)
                .ok()
                .filter(|&limit| input.len() > limit)
        });
        Self {
            input,
            position: 0,
            limit_end,
            collection_limit: config.collection_limit,
            depth_limit: config.depth_limit,
            depth: 0,
        }
    }

    /// Enforces the byte limit at `end`, returning the configured limit on
    /// overflow. `limit_end` is `None` in the common case, so this inlines to
    /// nothing after the compiler hoists the invariant branch.
    #[inline(always)]
    fn enforce_limit(&self, end: usize) -> Result<()> {
        if let Some(end_limit) = self.limit_end {
            if end > end_limit {
                return Err(Error::SizeLimit {
                    limit: end_limit as u64,
                });
            }
        }
        Ok(())
    }

    /// The number of bytes consumed so far.
    pub const fn position(&self) -> usize {
        self.position
    }

    /// The number of bytes remaining.
    pub const fn remaining(&self) -> usize {
        self.input.len() - self.position
    }

    /// Takes `len` bytes, enforcing the byte limit.
    #[inline]
    fn take(&mut self, len: usize) -> Result<&'de [u8]> {
        let end = self.position.checked_add(len).ok_or(Error::UnexpectedEnd)?;
        self.enforce_limit(end)?;
        let bytes = self
            .input
            .get(self.position..end)
            .ok_or(Error::UnexpectedEnd)?;
        self.position = end;
        Ok(bytes)
    }

    /// Advances past one byte that `self.input[position]` is known to hold.
    ///
    /// Inlined into the single-byte decode fast paths so the dominant case
    /// (values ≤ 250, booleans, bytes) never builds a range slice.
    #[inline]
    fn advance_one(&mut self, position: usize) -> Result<()> {
        let end = position + 1;
        self.enforce_limit(end)?;
        self.position = end;
        Ok(())
    }

    /// Reads one raw byte.
    #[inline]
    pub(crate) fn byte(&mut self) -> Result<u8> {
        let position = self.position;
        match self.input.get(position) {
            Some(&byte) => {
                self.advance_one(position)?;
                Ok(byte)
            }
            None => Err(Error::UnexpectedEnd),
        }
    }

    /// Reads a canonical marker-varint as `u64`.
    ///
    /// The single-byte case (`value ≤ 250`) is inlined so numeric-array hot
    /// loops pay one bounds check and one branch per element, not the full
    /// `take` machinery.
    #[inline]
    pub(crate) fn read_varint(&mut self) -> Result<u64> {
        let position = self.position;
        match self.input.get(position) {
            None => Err(Error::UnexpectedEnd),
            Some(&marker) if marker <= 250 => {
                self.advance_one(position)?;
                Ok(marker as u64)
            }
            Some(&marker) => {
                // `position < input.len()` and the widths are ≤ 17, so the
                // sum cannot overflow (slices are capped at `isize::MAX`).
                let end = position
                    + match marker {
                        MARKER_U16 => 3,
                        MARKER_U32 => 5,
                        MARKER_U64 => 9,
                        MARKER_U128 => 17,
                        other => return Err(Error::InvalidVarintMarker(other)),
                    };
                self.enforce_limit(end)?;
                let bytes = self
                    .input
                    .get(position + 1..end)
                    .ok_or(Error::UnexpectedEnd)?;
                self.position = end;
                if marker == MARKER_U128 {
                    // A `u64` read hitting a 128-bit marker: the payload may
                    // be a valid canonical varint whose value exceeds
                    // `u64::MAX` — that is an overflow, not a canonicality
                    // failure.
                    let value = decode_varint_le(marker, bytes).ok_or(Error::NonCanonicalVarint)?;
                    u64::try_from(value).map_err(|_| Error::IntegerOverflow { target: "u64" })
                } else {
                    decode_varint_le_u64(marker, bytes).ok_or(Error::NonCanonicalVarint)
                }
            }
        }
    }

    /// Reads a canonical marker-varint as `u128`.
    #[inline]
    pub(crate) fn read_varint_u128(&mut self) -> Result<u128> {
        let position = self.position;
        match self.input.get(position) {
            None => Err(Error::UnexpectedEnd),
            Some(&marker) if marker <= 250 => {
                self.advance_one(position)?;
                Ok(marker as u128)
            }
            Some(&marker) => {
                // `position < input.len()` and the widths are ≤ 17, so the
                // sum cannot overflow (slices are capped at `isize::MAX`).
                let end = position
                    + match marker {
                        MARKER_U16 => 3,
                        MARKER_U32 => 5,
                        MARKER_U64 => 9,
                        MARKER_U128 => 17,
                        other => return Err(Error::InvalidVarintMarker(other)),
                    };
                self.enforce_limit(end)?;
                let bytes = self
                    .input
                    .get(position + 1..end)
                    .ok_or(Error::UnexpectedEnd)?;
                self.position = end;
                decode_varint_le(marker, bytes).ok_or(Error::NonCanonicalVarint)
            }
        }
    }

    /// Reads a ZigZag marker-varint as `i64` (range-checked).
    #[inline]
    pub(crate) fn read_zigzag(&mut self) -> Result<i64> {
        let encoded = self.read_varint_u128()?;
        let value = zigzag_decode(encoded);
        i64::try_from(value).map_err(|_| Error::IntegerOverflow { target: "i64" })
    }

    /// Reads a ZigZag marker-varint as `i128`.
    #[inline]
    pub(crate) fn read_zigzag_i128(&mut self) -> Result<i128> {
        Ok(zigzag_decode(self.read_varint_u128()?))
    }

    /// Reads a one-byte boolean.
    #[inline]
    pub(crate) fn read_bool(&mut self) -> Result<bool> {
        match self.byte()? {
            0 => Ok(false),
            1 => Ok(true),
            other => Err(Error::InvalidBool(other)),
        }
    }

    /// Reads a little-endian `f32`.
    #[inline]
    pub(crate) fn read_f32(&mut self) -> Result<f32> {
        let bytes = self.take(4)?;
        Ok(f32::from_le_bytes(bytes.try_into().expect("fixed width")))
    }

    /// Reads a little-endian `f64`.
    #[inline]
    pub(crate) fn read_f64(&mut self) -> Result<f64> {
        let bytes = self.take(8)?;
        Ok(f64::from_le_bytes(bytes.try_into().expect("fixed width")))
    }

    /// Reads a collection length as `usize`.
    #[inline]
    pub(crate) fn read_length(&mut self) -> Result<usize> {
        let value = self.read_varint()?;
        usize::try_from(value).map_err(|_| Error::IntegerOverflow { target: "usize" })
    }

    /// Reads `len` raw bytes (bounded by the byte limit).
    #[inline]
    pub(crate) fn read_bytes(&mut self, len: usize) -> Result<&'de [u8]> {
        self.take(len)
    }

    /// Reads a length-prefixed UTF-8 string, borrowing the input.
    #[inline]
    pub(crate) fn read_str(&mut self) -> Result<&'de str> {
        let len = self.read_length()?;
        let bytes = self.take(len)?;
        core::str::from_utf8(bytes).map_err(Error::InvalidUtf8)
    }

    /// Validates and books a length-prefixed container.
    ///
    /// Applies the collection limit to `len` and increments the nesting depth
    /// (guarding against adversarial deep nesting). The matching
    /// [`exit_container`](CompactCursor::exit_container) must be called after
    /// the element loop.
    #[inline]
    pub(crate) fn enter_container(&mut self, len: usize) -> Result<()> {
        if let Some(limit) = self.collection_limit {
            if len as u64 > limit {
                return Err(Error::CollectionLimit { limit });
            }
        }
        if self.depth >= self.depth_limit {
            return Err(Error::Custom(
                "compact decode nesting depth limit exceeded".into(),
            ));
        }
        self.depth += 1;
        Ok(())
    }

    /// Bulk-decodes `len` marker-varints into a fresh vector.
    ///
    /// Contiguous runs of single-byte varints (`value ≤ 250`) are consumed as
    /// a contiguous byte run — one bounds check per run instead of per
    /// element — which is the dominant shape of numeric arrays in practice.
    /// Multi-byte varints are decoded with the marker fetched exactly once, so
    /// all-multi-byte data costs the same as the per-element reader.
    pub(crate) fn read_varints_bulk(&mut self, len: usize) -> Result<Vec<u64>> {
        let mut out = Vec::new();
        out.try_reserve_exact(len)
            .map_err(|_| Error::SizeLimit { limit: u64::MAX })?;
        let mut remaining = len;
        while remaining > 0 {
            let position = self.position;
            match self.input.get(position) {
                None => return Err(Error::UnexpectedEnd),
                Some(&marker) if marker <= 250 => {
                    // Consume the whole plain run (at least this byte).
                    let available = &self.input[position + 1..];
                    let window = &available[..(remaining - 1).min(available.len())];
                    let extra = plain_varint_prefix(window).min(remaining - 1);
                    let end = position + 1 + extra;
                    self.enforce_limit(end)?;
                    for &byte in &self.input[position..end] {
                        out.push(byte as u64);
                    }
                    self.position = end;
                    remaining -= 1 + extra;
                }
                Some(&marker) => {
                    // `position < input.len()` and the widths are ≤ 17, so the
                    // sum cannot overflow (slices are capped at `isize::MAX`).
                    let end = position
                        + match marker {
                            MARKER_U16 => 3,
                            MARKER_U32 => 5,
                            MARKER_U64 => 9,
                            MARKER_U128 => 17,
                            other => return Err(Error::InvalidVarintMarker(other)),
                        };
                    self.enforce_limit(end)?;
                    let bytes = self
                        .input
                        .get(position + 1..end)
                        .ok_or(Error::UnexpectedEnd)?;
                    if marker == MARKER_U128 {
                        // A `Vec<u64>` element hitting a 128-bit marker: the
                        // payload may be a valid canonical varint above
                        // `u64::MAX` — that is an overflow, not a
                        // canonicality failure.
                        let value =
                            decode_varint_le(marker, bytes).ok_or(Error::NonCanonicalVarint)?;
                        out.push(
                            u64::try_from(value)
                                .map_err(|_| Error::IntegerOverflow { target: "u64" })?,
                        );
                    } else {
                        out.push(
                            decode_varint_le_u64(marker, bytes).ok_or(Error::NonCanonicalVarint)?,
                        );
                    }
                    self.position = end;
                    remaining -= 1;
                }
            }
        }
        Ok(out)
    }

    /// Leaves the innermost length-prefixed container.
    #[inline]
    pub(crate) fn exit_container(&mut self) {
        debug_assert!(self.depth > 0);
        self.depth -= 1;
    }
}

/// Bulk `f64` conversion honoring alignment; falls back to per-value
/// `from_le_bytes` when the input slice is not 8-byte aligned.
fn read_f64_vec(cursor: &mut CompactCursor<'_>, len: usize) -> Result<Vec<f64>> {
    let byte_len = len
        .checked_mul(core::mem::size_of::<f64>())
        .ok_or(Error::IntegerOverflow { target: "usize" })?;
    let bytes = cursor.read_bytes(byte_len)?;
    let mut out = Vec::new();
    out.try_reserve_exact(len)
        .map_err(|_| Error::SizeLimit { limit: u64::MAX })?;
    if cfg!(target_endian = "little")
        && (bytes.as_ptr() as usize) % core::mem::align_of::<f64>() == 0
    {
        // SAFETY: `f64` has no invalid bit patterns and no padding; the
        // alignment check above makes the cast sound, and the target is
        // little-endian so the bytes already are the values. Read-only.
        let values = unsafe { core::slice::from_raw_parts(bytes.as_ptr().cast::<f64>(), len) };
        out.copy_from_slice(values);
    } else {
        for chunk in bytes.chunks_exact(core::mem::size_of::<f64>()) {
            out.push(f64::from_le_bytes(
                chunk.try_into().expect("chunks_exact yields 8 bytes"),
            ));
        }
    }
    Ok(out)
}

