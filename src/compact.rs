    fn roundtrip<T>(value: &T) -> Vec<u8>
    where
        T: CompactEncode + for<'de> CompactDecode<'de> + PartialEq + core::fmt::Debug,
    {
        let config = Config::standard();
        let compact = CompactConfig::new(config);
        let bytes = compact.serialize(value).unwrap();
        let decoded: T = compact.deserialize(&bytes).unwrap();
        assert_eq!(decoded, *value);
        bytes
    }

    // The hand-inlined hot-path encode must never drift from the canonical
    // `encode_varint_le` that the single-value writer shares.
    #[test]
    fn inline_varint_write_matches_canonical() {
        let cases = [
            0u64,
            1,
            250,
            251,
            0xffff,
            0x1_0000,
            0xffff_ffff,
            0x1_0000_0000,
            u64::MAX,
        ];
        for value in cases {
            let mut buffer = [0u8; 32];
            let len = write_varint_into(&mut buffer, value);
            let (canonical, canonical_len) = crate::canonical::encode_varint_le(value as u128);
            assert_eq!(&buffer[..len], &canonical[..canonical_len], "value {value}");
            assert_eq!(len, canonical_len);
        }
    }

    // The batched writer and reader must agree with the single-value paths on
    // a dense value sweep (covers every varint width and the flush boundaries).
    #[test]
    fn bulk_paths_agree_with_single_value_paths() {
        let mut values = Vec::new();
        values.extend(0..300); // plain run
        values.push(251);
        values.push(0xffff);
        values.push(0x1_0000);
        values.push(0xffff_ffff);
        values.push(0x1_0000_0000);
        values.push(u64::MAX);
        // A sweep that forces many flush boundaries (5-byte values).
        values.extend((0..300).map(|i| 0x1_0000 + i));
        let config = Config::standard();
        let compact = CompactConfig::new(config);
        let bytes = compact.serialize(&values).unwrap();
        assert_eq!(compact.deserialize::<Vec<u64>>(&bytes).unwrap(), values);
    }

