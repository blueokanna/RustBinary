macro_rules! impl_tuple {
    ($($name:ident),+ $(,)?) => {
        impl<$($name: CompactEncode),+> CompactEncode for ($($name,)+) {
            #[allow(non_snake_case)]
            #[inline]
            fn encode_compact<W: EncodeWriter + ?Sized>(&self, writer: &mut W) -> Result<()> {
                let ($($name,)+) = self;
                $( $name.encode_compact(writer)?; )+
                Ok(())
            }
        }
        impl<'de, $($name: CompactDecode<'de>),+> CompactDecode<'de> for ($($name,)+) {
            #[allow(non_snake_case)]
            #[inline]
            fn decode_compact(cursor: &mut CompactCursor<'de>) -> Result<Self> {
                Ok(($( $name::decode_compact(cursor)?, )+))
            }
        }
    };
}

